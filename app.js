function configurarBuscaContos() {
  const input = document.getElementById("searchContos");
  const grid = document.getElementById("contosGrid");
  const filtros = document.querySelectorAll("[data-filter]");

  let filtroAtual = "Todos";

  function atualizar() {
    const termo = input ? input.value.toLowerCase().trim() : "";

    const resultado = contos.filter(conto => {
      const correspondeFiltro =
        filtroAtual === "Todos" || conto.categoria === filtroAtual;

      const texto = `
        ${conto.titulo}
        ${conto.categoria}
        ${conto.descricao}
      `.toLowerCase();

      const correspondeBusca = !termo || texto.includes(termo);

      return correspondeFiltro && correspondeBusca;
    });

    if (!resultado.length) {
      grid.innerHTML = `
        <div class="empty">
          <h2>
            Nenhuma história encontrada.
          </h2>
          <p>
            Tente outro termo de busca.
          </p>
        </div>
      `;
      return;
    }

    grid.innerHTML = resultado.map(criarCardConto).join("");
  }

  if (input) {
    input.addEventListener("input", atualizar);
  }

  filtros.forEach(botao => {
    botao.addEventListener("click", () => {
      filtros.forEach(b => b.classList.remove("on"));
      botao.classList.add("on");
      filtroAtual = botao.dataset.filter;
      atualizar();
    });
  });
}

