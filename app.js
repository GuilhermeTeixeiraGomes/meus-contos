function router() {
  let rota = location.hash.replace(/^#\/?/, "");

  if (!rota) {
    renderHome();
    return;
  }

  if (rota === "contos") {
    renderContos();
    return;
  }

  if (rota === "poemas") {
    renderPoemas();
    return;
  }

  if (rota === "sobre") {
    renderSobre();
    return;
  }

  if (rota === "autor") {
    renderAutor();
    return;
  }

  if (rota.startsWith("conto/")) {
    const id = rota.replace("conto/", "");
    renderConto(id);
    return;
  }

  if (rota.startsWith("poema/")) {
    const id = rota.replace("poema/", "");
    renderPoema(id);
    return;
  }

  render404();
}

